from datetime import date
import ft4222
import ft4222.I2CMaster
import time
import array

dev=None
SLAVE_ID = (0xA6>>1)

def initDevice():
    global dev
    try:
        dev = ft4222.openByDescription('FT4222 A')
        dev.i2cMaster_Init(400)#kbps
        dev.setTimeouts(3000, 3000)#3s
        print(dev)
    except Exception as e:
        print(e)

def closeDevice():
    global dev
    try:
        dev.close()
        return True
    except Exception as e:
        print(e)
        return False

def I2C_Write(addr, data):
    global dev
    if addr != 0xffff:
        cmd = [addr & 0xff, data & 0xff]
        try:
            dev.i2cMaster_Write(SLAVE_ID, bytes(cmd))
            return True
        except Exception as e:
            print("{}:{}".format(time.strftime("%Y.%m.%d %H:%M:%S", time.localtime()), e))
            return False
    else:
        time.sleep(data/1000)
        print("{}:{}".format(time.strftime("%Y.%m.%d %H:%M:%S", time.localtime()), "delay {}ms".format(data)))

